function distinctValidValues(schema: ValueSchema, seed: unknown, count: number): unknown[] {
  const result: unknown[] = [];
  const seen = new Set<string>();
  const add = (candidate: unknown): void => {
    try { validateValue(schema, candidate); } catch { return; }
    const encoded = JSON.stringify(candidate);
    if (!seen.has(encoded)) { seen.add(encoded); result.push(candidate); }
  };
  add(seed);
  if (schema.kind === "string") {
    if (schema.allowed) schema.allowed.forEach(add);
    for (let index = 0; result.length < count && index < count * 4; index++) {
      const suffix = index.toString(36);
      if (schema.format === "sha256") add(index.toString(16).padStart(64, "0"));
      else if (schema.format === "base64") add(Buffer.from(`fixture-${index}`, "utf8").toString("base64"));
      else if (schema.format === "uri" && typeof seed === "string") {
        try { const uri = new URL(seed); uri.searchParams.set("rrFixture", suffix); add(uri.toString()); } catch {}
      } else if (schema.format === "absolute-path") add(`/fixture-${suffix}`);
      else {
        const available = Math.max(0, (schema.maximumLength ?? 4096) - suffix.length);
        add(`${typeof seed === "string" ? seed.slice(0, available) : "x"}${suffix}`);
        add(`x${suffix}`);
      }
    }
  } else if (schema.kind === "integer") {
    const minimum = schema.minimum ?? 0;
    const maximum = schema.maximum ?? Number.MAX_SAFE_INTEGER;
    for (let candidate = minimum; result.length < count && candidate <= maximum; candidate++) add(candidate);
  } else if (schema.kind === "boolean") {
    add(false); add(true);
  } else if (schema.kind === "null") add(null);
  else if (schema.kind === "nullable") {
    add(null);
    distinctValidValues(schema.value, seed, count).forEach(add);
  } else if (schema.kind === "union") {
    for (const choice of schema.choices) distinctValidValues(choice, seed, count).forEach(add);
  } else if (schema.kind === "object" && seed && typeof seed === "object" && !Array.isArray(seed)) {
    for (const [key, childSchema] of Object.entries(schema.properties)) {
      const childSeed = (seed as Record<string, unknown>)[key];
      if (childSeed === undefined) continue;
      for (const childValue of distinctValidValues(childSchema, childSeed, count)) add({ ...(seed as Record<string, unknown>), [key]: childValue });
      if (result.length >= count) break;
    }
  } else if (schema.kind === "map" && seed && typeof seed === "object" && !Array.isArray(seed)) {
    const entries = Object.entries(seed as Record<string, unknown>);
    if (entries.length) {
      const [key, childSeed] = entries[0]!;
      for (const childValue of distinctValidValues(schema.values, childSeed, count)) add({ ...(seed as Record<string, unknown>), [key]: childValue });
    }
  } else if (schema.kind === "array" && Array.isArray(seed) && seed.length) {
    for (const childValue of distinctValidValues(schema.items, seed[0], count)) add([childValue, ...seed.slice(1)]);
  }
  return result.slice(0, count);
}

function boundaryMutations(schema: ValueSchema, value: unknown, path = "document"): Mutation[] {
  const result: Mutation[] = [];
  if (schema.kind === "integer" && typeof value === "number") {
    if (schema.minimum !== undefined) result.push({ value: schema.minimum - 1, label: `${path}:minimum` });
    // MAX_SAFE_INTEGER is the browser representation ceiling for Java long fields, not a
    // resolver ceiling. There is no exact JSON number above it that the UI can round-trip.
    if (schema.maximum !== undefined && schema.maximum < Number.MAX_SAFE_INTEGER) result.push({ value: schema.maximum + 1, label: `${path}:maximum` });
  }
  if (schema.kind === "string" && typeof value === "string") {
    if (schema.minimumLength !== undefined && schema.minimumLength > 0) result.push({ value: "", label: `${path}:minimumLength` });
    if (schema.maximumLength !== undefined) result.push({ value: "x".repeat(schema.maximumLength + 1), label: `${path}:maximumLength` });
    if (schema.allowed) result.push({ value: "not-an-allowed-value", label: `${path}:allowed` });
    if (schema.pattern) result.push({ value: "!invalid!", label: `${path}:pattern` });
    if (schema.schemes) result.push({ value: `ftp://${new URL(value).host}/invalid`, label: `${path}:scheme` });
    if (schema.allowFragment === false && schema.format === "uri") result.push({ value: `${value}#fragment`, label: `${path}:fragment` });
    if (schema.format === "sha256") result.push({ value: "A".repeat(64), label: `${path}:sha256` });
    if (schema.format === "base64") result.push({ value: "not base64", label: `${path}:base64` });
  }
  const child = (childSchema: ValueSchema, childValue: unknown, childPath: string, replace: (replacement: unknown) => unknown): void => {
    for (const mutation of boundaryMutations(childSchema, childValue, childPath)) result.push({ value: replace(mutation.value), label: mutation.label });
  };
  if (schema.kind === "object" && value && typeof value === "object" && !Array.isArray(value)) {
    for (const [key, childSchema] of Object.entries(schema.properties)) if (key in (value as Record<string, unknown>)) {
      child(childSchema, (value as Record<string, unknown>)[key], `${path}.${key}`,
        (replacement) => ({ ...(value as Record<string, unknown>), [key]: replacement }));
    }
  }
  if (schema.kind === "map" && value && typeof value === "object" && !Array.isArray(value)) {
    for (const [key, item] of Object.entries(value as Record<string, unknown>)) child(schema.values, item, `${path}.${key}`,
      (replacement) => ({ ...(value as Record<string, unknown>), [key]: replacement }));
  }
  if (schema.kind === "array" && Array.isArray(value)) {
    if (schema.minimumItems !== undefined && schema.minimumItems > 0) result.push({ value: [], label: `${path}:minimumItems` });
    if (schema.maximumItems !== undefined && value.length) {
      const items = distinctValidValues(schema.items, value[0], schema.maximumItems + 1);
      if (items.length > schema.maximumItems) result.push({ value: items, label: `${path}:maximumItems` });
    }
    value.forEach((item, index) => child(schema.items, item, `${path}[${index}]`, (replacement) => { const copy = [...value]; copy[index] = replacement; return copy; }));
  }
  if (schema.kind === "nullable" && value !== null) child(schema.value, value, path, (replacement) => replacement);
  if (schema.kind === "union") for (const choice of schema.choices) { try { child(choice, value, path, (replacement) => replacement); break; } catch {} }
  return result;
}

