import { expect, test } from '@playwright/test';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
const ORIGIN = process.env.RAVENROOT_DEPLOYMENT_PERSISTENCE_ORIGIN;
const EXTERNAL = process.env.RAVENROOT_LAKEHOUSE_EXTERNAL;
const OUTPUT = process.env.RAVENROOT_HISTORY_EVIDENCE_DIR;
test('executed lakehouse shows concurrent filenames, four of six, reconnect and actual gold continuation', async ({ page, request }) => {
  test.setTimeout(110_000); page.setDefaultTimeout(15_000);
  if (!ORIGIN || !EXTERNAL || !OUTPUT) throw new Error('requires actual executed lakehouse server');
  const pages = [], pending = [], errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('response', response => { const url = new URL(response.url()); if (!url.pathname.endsWith('/history')) return;
    pending.push((async () => { const body = await response.body(); const data = JSON.parse(body); pages.push({ view: url.searchParams.get('view'), bytes: body.length,
      rows: data.items?.length || 0, duration: response.request().timing().responseEnd, status: response.status() }); })()); });
  await page.setViewportSize({ width: 1500, height: 1100 });
  await page.goto(ORIGIN); await expect(page.locator('#runtime-connection')).toHaveClass(/connected/, { timeout: 30_000 });
  await page.evaluate(() => window.ravenroot.setApplicationTheme('light'));
  await page.locator('#menu-run').click(); await page.getByRole('menuitem', { name: 'Deployments…' }).click();
  await page.locator('[data-deployment-view="lakehouse-example"]').click();
  await expect.poll(() => page.evaluate(() => window.ravenroot.activeDocument()?.graph?.viewerBinding?.deploymentId)).toBe('lakehouse-example');
  await page.locator('[data-menu="layout"]').click(); await page.getByRole('menuitemradio', { name: 'Monitoring', exact: true }).click();
  const monitor = page.locator('.doc-history'); await expect(monitor).toBeVisible();
  const section = name => monitor.locator('.history-page').filter({ has: page.getByRole('heading', { name, exact: true }) });
  const histories = section('Business histories'); await expect(histories.locator('li')).toHaveCount(3);
  await expect(histories.getByRole('button', { name: /ingest-sales-v1/ })).toContainText('sales.csv');
  await expect(histories.getByRole('button', { name: /ingest-sales-v2/ })).toContainText('sales.csv');
  await page.screenshot({ path: join(OUTPUT, 'lakehouse-concurrent-ingestions.png'), fullPage: true });
  await histories.getByRole('button', { name: /ingest-sales-v1/ }).click();
  const rounds = section('Join rounds'); await expect(rounds).toContainText('4/6 contributions');
  await rounds.getByRole('button', { name: /six-partitions/ }).click();
  const members = section('Contributions'); await expect(members.locator('li')).toHaveCount(6);
  const missing = members.locator('li').filter({ hasText: 'Expected and missing' }); await expect(missing).toHaveCount(2);
  await expect(members).toContainText('part-5'); await expect(members).toContainText('part-6');
  await page.screenshot({ path: join(OUTPUT, 'lakehouse-four-of-six.png'), fullPage: true });
  await rounds.screenshot({ path: join(OUTPUT, 'lakehouse-four-of-six-round.png') });
  await members.screenshot({ path: join(OUTPUT, 'lakehouse-four-of-six-members.png') });
  const traversals = section('Actual traversals'); await expect(traversals.locator('li')).toHaveCount(5);
  await traversals.getByRole('button', { name: /Entry landing/ }).click();
  let preview = monitor.locator('.history-traversal').first();
  await expect(preview.locator('[data-design-element="bronze"]')).toBeVisible();
  await preview.locator('[data-design-element="bronze"]').click();
  await expect(preview.locator('.history-inspector')).toContainText('Total visits 1');
  await preview.locator('.history-page').filter({ has: page.getByRole('heading', { name: 'Visits', exact: true }) }).locator('li button').first().click();
  await expect(preview.locator('.history-inspector')).toContainText('Attempts');
  const canvas = preview.locator('[data-viewer-canvas]'); await canvas.scrollIntoViewIfNeeded();
  await expect.poll(() => canvas.evaluate(node => { const cy = node._cyreg.cy, box = cy.elements().renderedBoundingBox(); return box.w > 100 && box.x1 >= -2 && box.x2 <= node.clientWidth + 2; })).toBe(true);
  await page.screenshot({ path: join(OUTPUT, 'lakehouse-bronze-traversal.png'), fullPage: true });
  const release = await request.post(`${EXTERNAL}/release`); expect(release.status()).toBe(200);
  // Explicit bounded refresh after source reconnect; no page routes or store-shaped responses.
  await monitor.locator(':scope > details').first().locator(':scope > summary').click();
  await histories.getByRole('button', { name: 'Refresh page', exact: true }).click();
  await expect(histories.getByRole('button', { name: /ingest-sales-v1/ })).toContainText('COMPLETED', { timeout: 20_000 });
  await histories.getByRole('button', { name: /ingest-sales-v1/ }).click();
  await expect(rounds).toContainText('6/6 contributions'); await expect(rounds).toContainText('DISPATCHED');
  await rounds.getByRole('button', { name: /six-partitions/ }).click();
  await expect(members.locator('li')).toHaveCount(6); await expect(members.locator('li').filter({ hasText: 'Expected and missing' })).toHaveCount(0);
  await page.screenshot({ path: join(OUTPUT, 'lakehouse-six-complete.png'), fullPage: true });
  await rounds.screenshot({ path: join(OUTPUT, 'lakehouse-six-complete-round.png') });
  await members.screenshot({ path: join(OUTPUT, 'lakehouse-six-complete-members.png') });
  await expect(traversals.locator('li')).toHaveCount(8);
  await traversals.getByRole('button', { name: /Entry six-partitions/ }).click();
  preview = monitor.locator('.history-traversal').first();
  await preview.locator('[data-design-element="gold"]').click();
  await expect(preview.locator('.history-inspector')).toContainText('Total visits 1');
  await preview.locator('.history-page').filter({ has: page.getByRole('heading', { name: 'Visits', exact: true }) }).locator('li button').first().click();
  await expect(preview.locator('.history-inspector')).toContainText('COMPLETED');
  await preview.locator('[data-viewer-canvas]').scrollIntoViewIfNeeded();
  await page.screenshot({ path: join(OUTPUT, 'lakehouse-gold-continuation.png'), fullPage: true });
  await Promise.all(pending);
  const measurement = { historyRequests: pages.length, maximumPageBytes: Math.max(...pages.map(page => page.bytes)), maximumPageRows: Math.max(...pages.map(page => page.rows)),
    maximumLatencyMs: Math.max(...pages.map(page => page.duration)), monitorElements: await monitor.locator('*').count(), pages, errors };
  expect(measurement.maximumPageRows).toBeLessThanOrEqual(10); expect(measurement.maximumPageBytes).toBeLessThan(100_000); expect(measurement.monitorElements).toBeLessThan(3000); expect(errors).toEqual([]);
  writeFileSync(join(OUTPUT, 'lakehouse-browser-measurements.json'), JSON.stringify(measurement, null, 2));
});
