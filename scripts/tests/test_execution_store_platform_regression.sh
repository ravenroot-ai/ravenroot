#!/usr/bin/env sh
# Test_execution_store_platform.sh's Helm `existingClaim` invariant used `rg -q`, an
# undeclared dependency, directly inside an `if` condition. `set -eu` does not apply inside an `if`
# condition -- POSIX shell behaviour, not a `set -e` gap -- so when `rg` was absent the command
# exited 127, the `if` read that as false, the forbidden-pattern branch was skipped, and the script
# printed "passed" and exited 0 without ever having looked at the files. The fix replaced `rg` with
# `grep -F`, already used everywhere else in that script, closing the missing-binary path (grep is
# an unconditional, unguarded dependency of every `require_literal` call earlier in the same script;
# if it were ever absent, the script would already have failed loudly before reaching this check).
#
# What this script proves, and what a manual reproduction cannot: that the `existingClaim` branch
# itself still fires when the pattern is genuinely present, on every future CI run. A green run of
# test_execution_store_platform.sh proves nothing about that branch specifically -- it is equally
# green whether the branch works or is silently skipped, which is how the missing-binary failure went
# unnoticed. This RED/GREEN control injects the literal into a
# synthetic copy of the Helm files, show the target script turns RED, remove it, show GREEN again.
#
# A second forbidden literal in that script is RAVENROOT_ARTIFACT_PROVENANCE, which must
# not appear in the release image or in either production descriptor -- with the same negative-`if`
# shape and therefore the same way of rotting green. It gets the same treatment here, steps [4/8] and
# [5/8], rather than being trusted because the check next to it is tested.
#
# Runs entirely against a throwaway fixture tree in $TMPDIR, never against this repository's real
# deploy/ files -- safe to run on every CI invocation of platform-config-check, and it cannot corrupt
# a real deployment descriptor if interrupted mid-run.
#
# Usage: ./scripts/tests/test_execution_store_platform_regression.sh
set -eu

PROJECT_DIR=$(CDPATH='' cd -- "$(dirname -- "$0")/../.." && pwd)
TARGET_SCRIPT="$PROJECT_DIR/scripts/tests/test_execution_store_platform.sh"

WORKDIR=$(mktemp -d "${TMPDIR:-/tmp}/ravenroot-platform-guard.XXXXXX")
trap 'rm -rf "$WORKDIR"' EXIT

mkdir -p "$WORKDIR/scripts/tests" \
    "$WORKDIR/deploy/kubernetes" \
    "$WORKDIR/deploy/helm/ravenroot/templates"

cp "$TARGET_SCRIPT" "$WORKDIR/scripts/tests/test_execution_store_platform.sh"

reset_target_script() {
  cp "$TARGET_SCRIPT" "$WORKDIR/scripts/tests/test_execution_store_platform.sh"
}

write_clean_fixtures() {
  cat >"$WORKDIR/compose.yaml" <<'EOF'
services:
  ravenroot:
    environment:
      RAVENROOT_EXECUTION_STORE_DIR: /opt/ravenroot/data/execution-store
      RAVENROOT_ARTIFACT_STORE_DIR: /opt/ravenroot/data/artifact-store
    volumes:
      - ravenroot-audit-data:/opt/ravenroot/data
    read_only: true
volumes:
  ravenroot-audit-data: {}
EOF

  cat >"$WORKDIR/deploy/kubernetes/ravenroot.yaml" <<'EOF'
spec:
  replicas: 1
  strategy:
    type: Recreate
  template:
    spec:
      securityContext:
        fsGroup: 10001
      containers:
        - env:
            - name: RAVENROOT_EXECUTION_STORE_DIR
            - name: RAVENROOT_ARTIFACT_STORE_DIR
              value: /opt/ravenroot/data/artifact-store
          volumeMounts:
            - mountPath: /opt/ravenroot/data
          securityContext:
            readOnlyRootFilesystem: true
      volumes:
        - persistentVolumeClaim:
            claimName: ravenroot-data
            accessModes:
              - ReadWriteOnce
EOF

  cat >"$WORKDIR/deploy/helm/ravenroot/values.yaml" <<'EOF'
replicaCount: 1
persistence:
  accessModes:
    - ReadWriteOnce
securityContext:
  fsGroup: 10001
EOF

  cat >"$WORKDIR/deploy/helm/ravenroot/templates/deployment.yaml" <<'EOF'
spec:
  strategy:
    type: Recreate
  template:
    spec:
      containers:
        - env:
            - name: RAVENROOT_EXECUTION_STORE_DIR
            - name: RAVENROOT_ARTIFACT_STORE_DIR
              value: /opt/ravenroot/data/artifact-store
          volumeMounts:
            - mountPath: /opt/ravenroot/data
EOF

  cat >"$WORKDIR/deploy/helm/ravenroot/templates/pvc.yaml" <<'EOF'
kind: PersistentVolumeClaim
spec:
  storageClassName: {{ .Values.persistence.storageClassName }}
EOF

  : >"$WORKDIR/deploy/helm/ravenroot/values.schema.json"

  # The target script also reads the Dockerfile now, for the one literal it must
  # NOT contain. Only the runtime ENV block matters to that check, so the fixture is that block and
  # nothing else -- a faithful copy of the real Dockerfile would make this fixture something to keep
  # in sync for no gain.
  cat >"$WORKDIR/Dockerfile" <<'EOF'
FROM scratch
ENV RAVENROOT_PORT=8080 \
    RAVENROOT_AUTH_MODE=oidc
EOF
}

run_target() {
  ( cd "$WORKDIR" && sh scripts/tests/test_execution_store_platform.sh )
}

fail=0

write_clean_fixtures
echo "[1/8] GREEN baseline: no existingClaim anywhere -- expect exit 0" >&2
if out=$(run_target 2>&1); then
  case "$out" in
    *"passed"*) echo "OK: baseline passed" >&2 ;;
    *)
      echo "FAIL: baseline exit 0 but did not print the expected pass message:" >&2
      echo "$out" >&2
      fail=1
      ;;
  esac
else
  echo "FAIL: baseline expected to pass but exited non-zero:" >&2
  echo "$out" >&2
  fail=1
fi

echo "[2/8] RED control: inject 'existingClaim' into values.yaml -- expect exit 1" >&2
printf '\nexistingClaim: some-preexisting-pvc\n' >>"$WORKDIR/deploy/helm/ravenroot/values.yaml"
if out=$(run_target 2>&1); then
  echo "FAIL: the existingClaim invariant did NOT turn the script red -- the check is not enforced:" >&2
  echo "$out" >&2
  fail=1
else
  case "$out" in
    *"unverified existing PVC"*) echo "OK: RED reproduced -- the script rejected existingClaim" >&2 ;;
    *)
      echo "FAIL: script exited non-zero but not for the expected reason:" >&2
      echo "$out" >&2
      fail=1
      ;;
  esac
fi

echo "[3/8] back to GREEN: remove the injected literal -- expect exit 0 again" >&2
# Rewrite the whole fixture tree rather than trying to strip the appended line, so this step's
# correctness does not depend on the previous step's edit being reversible.
write_clean_fixtures
if out=$(run_target 2>&1); then
  case "$out" in
    *"passed"*) echo "OK: back to GREEN" >&2 ;;
    *)
      echo "FAIL: exit 0 but unexpected output:" >&2
      echo "$out" >&2
      fail=1
      ;;
  esac
else
  echo "FAIL: removing the injected literal did not restore a passing run:" >&2
  echo "$out" >&2
  fail=1
fi

echo "[4/8] RED control: set RAVENROOT_ARTIFACT_PROVENANCE in the Dockerfile -- expect exit 1" >&2
printf '\nENV RAVENROOT_ARTIFACT_PROVENANCE=unverified\n' >>"$WORKDIR/Dockerfile"
if out=$(run_target 2>&1); then
  echo "FAIL: the SEC-12 provenance invariant did NOT turn the script red -- the check is not enforced:" >&2
  echo "$out" >&2
  fail=1
else
  case "$out" in
    *"must not set RAVENROOT_ARTIFACT_PROVENANCE"*)
      echo "OK: RED reproduced -- the script rejected the opt-in in the image" >&2 ;;
    *)
      echo "FAIL: script exited non-zero but not for the expected reason:" >&2
      echo "$out" >&2
      fail=1
      ;;
  esac
fi

echo "[5/8] RED control: set it in the Helm deployment template instead -- expect exit 1" >&2
# Not redundant with [4/8]: the two are separate forbid calls on separate files, and a check that
# only ever ran against the Dockerfile would leave the descriptor a chart author actually edits
# unguarded. Written as a templated value, which is the form a literal search for `unverified` would
# have missed and the reason this contract forbids the variable name instead.
write_clean_fixtures
printf '\n            - name: RAVENROOT_ARTIFACT_PROVENANCE\n              value: {{ .Values.provenance }}\n' \
    >>"$WORKDIR/deploy/helm/ravenroot/templates/deployment.yaml"
if out=$(run_target 2>&1); then
  echo "FAIL: the SEC-12 provenance invariant is not enforced on the Helm deployment template:" >&2
  echo "$out" >&2
  fail=1
else
  case "$out" in
    *"must not set RAVENROOT_ARTIFACT_PROVENANCE"*)
      echo "OK: RED reproduced -- the script rejected the opt-in in the chart" >&2 ;;
    *)
      echo "FAIL: script exited non-zero but not for the expected reason:" >&2
      echo "$out" >&2
      fail=1
      ;;
  esac
fi

echo "[6/8] RED control: delete the Dockerfile entirely -- expect exit 1, NOT a silent pass" >&2
# The provenance check originally used a bare `grep` on a single operand inside an `if`: with the
# file missing, grep exits 2,
# `set -eu` does not apply in an `if` condition, the branch is read as "no match", and the script
# printed "passed" with exit 0 having checked nothing. Measured before the fix:
#
#   grep: .../Dockerfile: No such file or directory
#   execution-store platform contracts passed.
#   EXIT=0
#
# Steps [4/8] and [5/8] cannot catch this: both inject a pattern into a file that exists, so both
# stay green whether the guard is present or absent. Only removing the operand separates the two,
# which is why "the check is correct now" is not a claim this suite could otherwise support. Deleting
# rather than emptying is deliberate -- an empty file is readable and legitimately contains no match,
# so it proves nothing about the missing-operand path.
write_clean_fixtures
rm -f "$WORKDIR/Dockerfile"
if out=$(run_target 2>&1); then
  echo "FAIL: a missing Dockerfile was read as a PASS -- the forbidden-pattern check never ran:" >&2
  echo "$out" >&2
  fail=1
else
  case "$out" in
    *"was never checked"*) echo "OK: RED reproduced -- an unreadable operand fails closed" >&2 ;;
    *)
      echo "FAIL: script exited non-zero but not for the expected reason:" >&2
      echo "$out" >&2
      fail=1
      ;;
  esac
fi

echo "[7/8] RED control: replace the Dockerfile with a directory -- expect exit 1" >&2
# Separate from [6/8] because the guard's two operators fail on different inputs, and this step pins
# exactly one of them. Measured: a directory IS `-r` readable, so an `-r`-only guard admits it and
# this step goes red; an `-f`-only guard rejects it, so this step alone does NOT justify keeping
# `-r`. That is what [8/8] is for -- written only after measuring that an `-f`-only guard survived
# steps 1 to 7 intact, so the stronger claim ("makes dropping either
# operator red") false.
write_clean_fixtures
rm -f "$WORKDIR/Dockerfile"
mkdir -p "$WORKDIR/Dockerfile"
if out=$(run_target 2>&1); then
  echo "FAIL: a Dockerfile that is a directory was read as a PASS:" >&2
  echo "$out" >&2
  fail=1
else
  case "$out" in
    *"was never checked"*) echo "OK: RED reproduced -- a non-regular-file operand fails closed" >&2 ;;
    *)
      echo "FAIL: script exited non-zero but not for the expected reason:" >&2
      echo "$out" >&2
      fail=1
      ;;
  esac
fi
rmdir "$WORKDIR/Dockerfile"

echo "[8/8] RED control: make the Dockerfile unreadable -- expect exit 1" >&2
# The other half of the guard, and the step whose absence made [7/8]'s first comment untrue: measured
# A guard testing only `-f` passed steps 1 through 7 unchanged, because nothing until
# here presents a REGULAR file that cannot be read. `-f` is true for it, `grep` then exits 2, and the
# `if` reads that as "no match".
#
# Skipped, loudly, when running as root: root reads a 000-mode file regardless, so the fixture cannot
# express the condition and the step would report a failure of the guard where there is none. A skip
# that announces itself is not the silent pass this suite exists to prevent -- the reason is on
# stderr and the exit status is untouched.
write_clean_fixtures
if [ "$(id -u)" = "0" ]; then
  echo "SKIP: running as root, which can read a 000-mode file; this control cannot be expressed" >&2
else
  chmod 000 "$WORKDIR/Dockerfile"
  if out=$(run_target 2>&1); then
    echo "FAIL: an unreadable Dockerfile was read as a PASS:" >&2
    echo "$out" >&2
    fail=1
  else
    case "$out" in
      *"was never checked"*) echo "OK: RED reproduced -- an unreadable regular file fails closed" >&2 ;;
      *)
        echo "FAIL: script exited non-zero but not for the expected reason:" >&2
        echo "$out" >&2
        fail=1
        ;;
    esac
  fi
  chmod 644 "$WORKDIR/Dockerfile"
fi

